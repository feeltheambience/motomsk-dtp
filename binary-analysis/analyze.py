#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Анализ бинарной последовательности (0/1) на предмет закономерностей,
позволяющих предсказывать следующий символ лучше случайного угадывания.

Система оценки: правильный прогноз +1, неправильный -1.
Цель: положительное математическое ожидание на длинной дистанции.

Запуск:  python3 analyze.py [путь_к_sequence.txt]

Автор исследования: скрипт полностью самодостаточен и воспроизводим.
"""
import sys, math, collections

# ---------------------------------------------------------------------------
# 1. Загрузка данных
# ---------------------------------------------------------------------------
def load_sequence(path="sequence.txt"):
    raw = open(path, encoding="utf-8").read()
    bits = [int(c) for c in raw if c in "01"]
    return bits

# ---------------------------------------------------------------------------
# 2. Тесты на случайность (проверяем, отличается ли ряд от «честной монеты»)
# ---------------------------------------------------------------------------
def randomness_tests(bits):
    n = len(bits)
    ones = sum(bits); zeros = n - ones
    print("=" * 68)
    print("1. БАЗОВАЯ СТАТИСТИКА И ТЕСТЫ НА СЛУЧАЙНОСТЬ")
    print("=" * 68)
    print(f"Длина последовательности N = {n}")
    print(f"Единиц: {ones} ({ones/n:.4f}),  Нулей: {zeros} ({zeros/n:.4f})")

    # Монобит-тест: смещена ли доля единиц от 0.5
    z_mono = (ones - n/2) / (math.sqrt(n)/2)
    print(f"\nМонобит-тест: z = {z_mono:+.3f}  "
          f"(|z|>1.96 => есть смещение доли единиц)")
    print("  -> Ряд практически сбалансирован: угадать по частоте нельзя.")

    # Тест серий (runs test): выявляет автокорреляцию / «липкость»
    runs = 1 + sum(1 for i in range(1, n) if bits[i] != bits[i-1])
    exp_runs = 2*ones*zeros/n + 1
    var_runs = 2*ones*zeros*(2*ones*zeros - n) / (n*n*(n-1))
    z_runs = (runs - exp_runs) / math.sqrt(var_runs)
    print(f"\nТест серий (runs test): наблюдаемо серий = {runs}, "
          f"ожидалось = {exp_runs:.0f}")
    print(f"  z = {z_runs:+.2f}   (|z|>1.96 => НЕслучайно)")
    print("  -> Серий значимо МЕНЬШЕ ожидаемого => положительная")
    print("     автокорреляция: одинаковые символы идут «сериями».")

    # Автокорреляция по лагам
    print("\nСовпадение символов на расстоянии lag (доля):")
    for lag in range(1, 6):
        m = sum(1 for i in range(n-lag) if bits[i] == bits[i+lag])
        print(f"  lag {lag}: {m/(n-lag):.4f}")
    print("  -> На lag=1 совпадение ~0.557 >> 0.5: главный сигнал.")

# ---------------------------------------------------------------------------
# 3. Марковские модели порядка k: подбор порядка на out-of-sample
# ---------------------------------------------------------------------------
def markov_order_sweep(bits, train_frac=0.70):
    n = len(bits)
    split = int(n*train_frac)
    print("\n" + "=" * 68)
    print("2. МАРКОВСКИЕ МОДЕЛИ РАЗНОГО ПОРЯДКА (train 70% / test 30%)")
    print("=" * 68)
    print("Порядок |  точность на тесте | верно/всего | счёт(+1/-1)")
    for k in range(1, 13):
        cnt = collections.defaultdict(lambda: [0, 0])
        for i in range(k, split):
            cnt[tuple(bits[i-k:i])][bits[i]] += 1
        c = t = 0
        for i in range(max(k, split), n):
            ctx = tuple(bits[i-k:i])
            v = cnt.get(ctx)
            if not v or v[0] == v[1]:
                continue
            pred = 1 if v[1] > v[0] else 0
            t += 1
            if pred == bits[i]:
                c += 1
        acc = c/t if t else 0
        print(f"  k={k:2d}   |      {acc:.4f}       | {c}/{t} | {2*c-t:+d}")
    print("  -> Порядки 1..5 дают одинаковый прогноз («повтори прошлый бит»)")
    print("     и максимум ~0.577. Большие порядки переобучаются (хуже).")

# ---------------------------------------------------------------------------
# 4. Итоговые стратегии и бэктест по системе +1/-1
# ---------------------------------------------------------------------------
def strategies(bits):
    n = len(bits)
    print("\n" + "=" * 68)
    print("3. ИТОГОВЫЕ СТРАТЕГИИ (бэктест на всей последовательности)")
    print("=" * 68)

    def report(name, correct, wrong):
        tot = correct + wrong
        acc = correct/tot if tot else 0
        z = (correct - tot/2)/(math.sqrt(tot)/2) if tot else 0
        print(f"\n{name}")
        print(f"   ставок={tot}  точность={acc:.4f}  верно={correct} "
              f"неверно={wrong}")
        print(f"   ИТОГОВЫЙ СЧЁТ = {correct-wrong:+d}   (z={z:+.1f})")

    # Стратегия A: без параметров — «следующий = предыдущий» (используем липкость)
    cA = sum(1 for i in range(1, n) if bits[i] == bits[i-1])
    report("A. «Повтори прошлый бит» (беспараметрическая, основная):",
           cA, (n-1)-cA)

    # Baseline: всегда 0
    c0 = sum(1 for b in bits if b == 0)
    report("   Базлайн «всегда 0» (для сравнения):", c0, n-c0)

    # Стратегия C: селективные ставки только на длинных сериях (momentum)
    print("\nC. Селективные ставки: играем только когда длина текущей")
    print("   серии >= L (прогноз — продолжение серии).")
    print("   L | точность | ставок | счёт")
    for L in range(1, 7):
        c = w = 0; rl = 1
        for i in range(1, n):
            if rl >= L:
                if bits[i] == bits[i-1]:
                    c += 1
                else:
                    w += 1
            rl = rl+1 if bits[i] == bits[i-1] else 1
        tot = c+w
        print(f"   {L} |  {c/tot:.4f} |  {tot:5d} | {c-w:+d}")
    print("   -> Чем длиннее серия, тем выше вероятность продолжения")
    print("      (эффект «импульса»): до ~0.60 при L>=6.")

# ---------------------------------------------------------------------------
def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "sequence.txt"
    bits = load_sequence(path)
    randomness_tests(bits)
    markov_order_sweep(bits)
    strategies(bits)
    print("\n" + "=" * 68)
    print("ВЫВОД: последовательность НЕ случайна. Устойчивая закономерность —")
    print("положительная автокорреляция (символы идут сериями). Правило")
    print("«следующий = предыдущий» даёт ~55.7% точности и счёт ~+2680,")
    print("что соответствует стабильно положительному мат. ожиданию.")
    print("=" * 68)

if __name__ == "__main__":
    main()
